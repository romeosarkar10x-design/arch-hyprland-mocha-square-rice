export function waybar(p: Palette): string {
  return `/* ~/.config/waybar/colors.css — @import "colors.css"; */
${Object.entries(p).map(([k, v]) => `@define-color ${k} ${v};`).join("\n")}
`;
}

export function rofi(p: Palette): string {
  return `/* ~/.config/rofi/colors.rasi — @import "colors.rasi" */
* {
${Object.entries(p).map(([k, v]) => `    ${k}: ${v};`).join("\n")}
    background-color: transparent;
    text-color: ${p.text};
    selected: ${p.mauve};
}
`;
}

export function swaync(p: Palette): string {
  return `/* ~/.config/swaync/colors.css */
${Object.entries(p).map(([k, v]) => `@define-color ${k} ${v};`).join("\n")}
@define-color noti-bg ${p.mantle};
@define-color noti-border ${p.surface0};
@define-color noti-accent ${p.mauve};
`;
}


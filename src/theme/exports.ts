// Palette -> dotfiles. One generator per program of the rice, so a wallpaper-derived theme
// can be dropped straight into ~/.config.

import { hexToLch, lchToHex, mix } from "./color.ts";
import { paletteCss, type Palette } from "./palette.ts";

/** The 16 ANSI colours, Catppuccin convention (black = surface1, magenta = pink, cyan = teal). */
export function ansi(p: Palette): string[] {
  const bright = (hex: string) => {
    const c = hexToLch(hex);
    return lchToHex({ l: Math.min(0.95, c.l + 0.04), c: c.c * 1.08, h: c.h });
  };
  const normal = [p.surface1, p.red, p.green, p.yellow, p.blue, p.pink, p.teal, mix(p.subtext0, p.text, 0.5)];
  const brights = [p.surface2, bright(p.red), bright(p.green), bright(p.yellow), bright(p.blue), bright(p.pink), bright(p.teal), p.subtext0];
  return [...normal, ...brights];
}

export const EMULATORS = ["ghostty", "kitty", "alacritty", "foot", "wezterm"] as const;
export type Emulator = (typeof EMULATORS)[number];
export type CursorShape = "block" | "beam" | "underline";

export interface TerminalOptions {
  font?: string;
  fontSize?: number;
  /** Background opacity, 0..1. Hyprland blurs what shows through. */
  opacity?: number;
  /** Inner padding in px. */
  padding?: number;
  cursor?: CursorShape;
  cursorBlink?: boolean;
  /** Kitty tab bar style. */
  tabStyle?: "powerline" | "slant" | "separator" | "fade" | "hidden";
}

const DEFAULTS: Required<TerminalOptions> = {
  font: "asiLonoM",
  fontSize: 12,
  opacity: 0.92,
  padding: 12,
  cursor: "block",
  cursorBlink: true,
  tabStyle: "powerline",
};

const bare = (hex: string) => hex.replace("#", "");

export function ghostty(p: Palette, o: TerminalOptions = {}): string {
  const c = { ...DEFAULTS, ...o };
  return `# ~/.config/ghostty/config — generated by arch-hyprland-mocha-square-rice
font-family = ${c.font}
font-size = ${c.fontSize}
font-feature = calt
font-feature = liga

background = ${bare(p.base)}
foreground = ${bare(p.text)}
cursor-color = ${bare(p.mauve)}
cursor-text = ${bare(p.crust)}
selection-background = ${bare(p.surface2)}
selection-foreground = ${bare(p.text)}
${ansi(p).map((hex, i) => `palette = ${i}=${hex}`).join("\n")}

background-opacity = ${c.opacity}
window-padding-x = ${c.padding}
window-padding-y = ${c.padding}
window-padding-balance = true
# Hyprland draws the border; no client-side decorations or GTK titlebar.
window-decoration = false
gtk-titlebar = false
cursor-style = ${c.cursor === "beam" ? "bar" : c.cursor}
cursor-style-blink = ${c.cursorBlink}
shell-integration-features = no-cursor
confirm-close-surface = false
`;
}

export function kitty(p: Palette, o: TerminalOptions = {}): string {
  const c = { ...DEFAULTS, ...o };
  return `# ~/.config/kitty/kitty.conf — generated by arch-hyprland-mocha-square-rice
font_family      ${c.font}
font_size        ${c.fontSize}
disable_ligatures never

foreground              ${p.text}
background              ${p.base}
selection_foreground    ${p.text}
selection_background    ${p.surface2}
cursor                  ${p.mauve}
cursor_text_color       ${p.crust}
url_color               ${p.blue}
active_border_color     ${p.mauve}
inactive_border_color   ${p.surface0}
bell_border_color       ${p.yellow}
mark1_background        ${p.lavender}
mark2_background        ${p.mauve}
mark3_background        ${p.sapphire}

tab_bar_edge            top
tab_bar_style           ${c.tabStyle}
tab_powerline_style     angled
active_tab_foreground   ${p.crust}
active_tab_background   ${p.mauve}
active_tab_font_style   bold
inactive_tab_foreground ${p.overlay1}
inactive_tab_background ${p.mantle}
tab_bar_background      ${p.crust}

${ansi(p).map((hex, i) => `color${i}`.padEnd(8) + hex).join("\n")}

background_opacity      ${c.opacity}
window_padding_width    ${c.padding}
cursor_shape            ${c.cursor}
cursor_blink_interval   ${c.cursorBlink ? "0.5" : "0"}
hide_window_decorations yes
confirm_os_window_close 0
enable_audio_bell       no
`;
}

export function alacritty(p: Palette, o: TerminalOptions = {}): string {
  const c = { ...DEFAULTS, ...o };
  const a = ansi(p);
  const names = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];
  const block = (from: number) => names.map((n, i) => `${n} = "${a[from + i]}"`).join("\n");
  return `# ~/.config/alacritty/alacritty.toml — generated by arch-hyprland-mocha-square-rice
[font]
normal = { family = "${c.font}" }
size = ${c.fontSize}

[window]
opacity = ${c.opacity}
padding = { x = ${c.padding}, y = ${c.padding} }
decorations = "None"
dynamic_padding = true

[cursor]
style = { shape = "${c.cursor === "beam" ? "Beam" : c.cursor === "underline" ? "Underline" : "Block"}", blinking = "${c.cursorBlink ? "On" : "Off"}" }

[colors.primary]
background = "${p.base}"
foreground = "${p.text}"
dim_foreground = "${p.overlay1}"

[colors.cursor]
text = "${p.crust}"
cursor = "${p.mauve}"

[colors.selection]
text = "${p.text}"
background = "${p.surface2}"

[colors.normal]
${block(0)}

[colors.bright]
${block(8)}
`;
}

export function foot(p: Palette, o: TerminalOptions = {}): string {
  const c = { ...DEFAULTS, ...o };
  const a = ansi(p).map(bare);
  return `# ~/.config/foot/foot.ini — generated by arch-hyprland-mocha-square-rice
[main]
font=${c.font}:size=${c.fontSize}
pad=${c.padding}x${c.padding} center

[cursor]
style=${c.cursor}
blink=${c.cursorBlink ? "yes" : "no"}
color=${bare(p.crust)} ${bare(p.mauve)}

[colors]
alpha=${c.opacity}
foreground=${bare(p.text)}
background=${bare(p.base)}
selection-foreground=${bare(p.text)}
selection-background=${bare(p.surface2)}
urls=${bare(p.blue)}
${a.slice(0, 8).map((hex, i) => `regular${i}=${hex}`).join("\n")}
${a.slice(8).map((hex, i) => `bright${i}=${hex}`).join("\n")}
`;
}

export function wezterm(p: Palette, o: TerminalOptions = {}): string {
  const c = { ...DEFAULTS, ...o };
  const a = ansi(p).map((hex) => `"${hex}"`);
  const shape = c.cursor === "beam" ? "Bar" : c.cursor === "underline" ? "Underline" : "Block";
  return `-- ~/.config/wezterm/wezterm.lua — generated by arch-hyprland-mocha-square-rice
local wezterm = require("wezterm")

return {
  font = wezterm.font("${c.font}"),
  font_size = ${c.fontSize},
  window_background_opacity = ${c.opacity},
  window_decorations = "NONE",
  window_padding = { left = ${c.padding}, right = ${c.padding}, top = ${c.padding}, bottom = ${c.padding} },
  default_cursor_style = "${c.cursorBlink ? "Blinking" : "Steady"}${shape}",
  use_fancy_tab_bar = false,
  hide_tab_bar_if_only_one_tab = true,
  colors = {
    foreground = "${p.text}",
    background = "${p.base}",
    cursor_bg = "${p.mauve}",
    cursor_fg = "${p.crust}",
    cursor_border = "${p.mauve}",
    selection_fg = "${p.text}",
    selection_bg = "${p.surface2}",
    split = "${p.surface0}",
    ansi = { ${a.slice(0, 8).join(", ")} },
    brights = { ${a.slice(8).join(", ")} },
    tab_bar = {
      background = "${p.crust}",
      active_tab = { bg_color = "${p.mauve}", fg_color = "${p.crust}", intensity = "Bold" },
      inactive_tab = { bg_color = "${p.mantle}", fg_color = "${p.overlay1}" },
      inactive_tab_hover = { bg_color = "${p.surface0}", fg_color = "${p.text}" },
      new_tab = { bg_color = "${p.crust}", fg_color = "${p.overlay1}" },
    },
  },
}
`;
}


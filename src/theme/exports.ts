const rgbaHex = (hex: string, alpha = "ff") => `rgba(${bare(hex)}${alpha})`;

export function hyprland(p: Palette): string {
  return `# ~/.config/hypr/colors.conf — source = ~/.config/hypr/colors.conf
${Object.entries(p).map(([k, v]) => `$${k} = ${rgbaHex(v)}`).join("\n")}

general {
    col.active_border = ${rgbaHex(p.mauve, "ee")} ${rgbaHex(p.pink, "ee")} ${rgbaHex(p.yellow, "ee")} 45deg
    col.inactive_border = ${rgbaHex(p.surface0, "cc")}
    border_size = 2
    gaps_in = 3
    gaps_out = 6
}

decoration {
    rounding = 0
    shadow {
        color = ${rgbaHex(p.crust, "dd")}
    }
}

group {
    col.border_active = ${rgbaHex(p.mauve)}
    col.border_inactive = ${rgbaHex(p.surface0)}
}

misc {
    background_color = ${rgbaHex(p.crust)}
}
`;
}

